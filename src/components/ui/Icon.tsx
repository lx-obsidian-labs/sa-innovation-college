const iconAnimationClasses: Record<string, string> = {
  "spin": "animate-spin",
  "pulse": "animate-pulse-slow",
  "bounce": "animate-bounce-icon",
  "wiggle": "animate-wiggle",
};

interface IconProps {
  name: IconName;
  className?: string;
  size?: number | string;
  animated?: "spin" | "pulse" | "bounce" | "wiggle";
  strokeWidth?: number;
  ariaHidden?: boolean;
  label?: string;
}

export default function Icon({
  name,
  className,
  size = 5,
  animated,
  strokeWidth = 1.5,
  ariaHidden = true,
  label,
}: IconProps) {
  const icon = ICON_PATHS[name];
  if (!icon) return null;

  const sizeClass = typeof size === "number" ? `w-${size} h-${size}` : size;
  const isFill = icon.fill;
  const viewBox = icon.viewBox || "0 0 24 24";

  return (
    <svg
      className={cn(
        "inline-block shrink-0 transition-all duration-200",
        sizeClass,
        animated && iconAnimationClasses[animated],
        className
      )}
      viewBox={viewBox}
      fill={isFill ? "currentColor" : "none"}
      stroke={isFill ? undefined : "currentColor"}
      strokeWidth={isFill ? undefined : strokeWidth}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden={ariaHidden}
      role={label ? "img" : undefined}
      aria-label={label}
    >
      {icon.paths.map((d, i) => (
        <path key={i} d={d} />
      ))}
    </svg>
  );
}
